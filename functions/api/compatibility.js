// ============================================================
// functions/api/compatibility.js
// URL: POST /api/compatibility
// Body: { name1, dob1, name2, dob2, score }
//
// Нийцлийн ХУВИЙГ (score) frontend дээр deterministic аргаар
// тооцдог тул энд дахин тооцохгүй — зөвхөн ирсэн score дээр
// үндэслэн зугаа цэнгээний зорилготой ДЭЛГЭРЭНГҮЙ ТАЙЛАН бичнэ.
//
// Энэ бол жинхэнэ зурхай/шинжлэх ухааны дүгнэлт БИШ, зөвхөн
// зугаа цэнгээний зорилготой контент гэдгийг AI-д тодорхой
// зааж өгнө.
// ============================================================
import { callAI, corsJson, corsOptions } from '../_shared/ai.js';

export async function onRequestOptions() {
  return corsOptions();
}

export async function onRequestPost({ request, env }) {
  try {
    const { name1, name2, score } = await request.json();

    if (!name1 || !name1.trim() || !name2 || !name2.trim()) {
      return corsJson({ error: 'Хоёр хүний нэрийг оруулна уу' }, 400);
    }
    const pct = Math.max(1, Math.min(100, parseInt(score, 10) || 50));

    const systemPrompt = `Чи хөгжилтэй, дулаан аястай "нийцлийн тайлан бичигч". Энэ бол ЗУГАА ЦЭНГЭЭНИЙ зорилготой контент — жинхэнэ зурхай, сэтгэл судлалын шинжлэх ухааны дүгнэлт БИШ гэдгийг чи сайн ойлгож байгаа тул хэт ноцтой, эсвэл хэт сөрөг зүйл бичихгүй.

ХАТУУ ДҮРЭМ:
1. Монгол хэлээр, дулаан, хөгжилтэй өнгө аястай бич.
2. 4 хэсэгтэй бич: (1) Ерөнхий зураглал 2-3 өгүүлбэр, (2) Давуу тал / юу сайн зохицож байгаа 2-3 өгүүлбэр, (3) Анхаарах зүйл / сорилт 2-3 өгүүлбэр (сөрөг бус, зөвлөмж хэлбэрээр), (4) Хамтдаа юу хийвэл тохирох вэ гэсэн 1-2 санал.
5. Label бүрийг **тод** тэмдэглэл болгож бич (жишээ: **Ерөнхий зураглал**).
6. Нийт 150-220 үг орчим бич.
7. Хэзээ ч "чи салах ёстой", "энэ хос тохирохгүй" гэх мэт эцсийн шийдвэр гаргах, эсвэл бодит амьдралын гэрлэлт/харилцааны талаар ноцтой зөвлөгөө өгөхгүй — энэ бол зөвхөн зугаа.`;

    const userText = `Хос: ${name1.trim()} болон ${name2.trim()}.
Нийцлийн хувь: ${pct}%.
Дээрх дүрмийн дагуу энэ хосын хувьд зугаа цэнгээний нийцлийн тайлан бич.`;

    const { text } = await callAI(env, systemPrompt, userText, {
      temperature: 0.85,
      maxOutputTokens: 700
    });

    return corsJson({ report: text });
  } catch (err) {
    return corsJson({ error: err.message }, 500);
  }
}
